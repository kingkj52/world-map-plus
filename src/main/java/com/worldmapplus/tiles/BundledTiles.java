/**
 * The tiles bundled in the plugin jar. Floors above the ground are tiles of their own, stored under
 * {@link TileSource#tileMapId(int, int)}, and are transparent wherever the floor has nothing.
 * <p>
 * Layout, all under {@code /com/worldmapplus/tiles/}:
 * <ul>
 * <li>{@code index.json}: which squares exist, per map, so a missing tile is known without
 * touching the jar;</li>
 * <li>{@code <mapId>/<x>_<y>.wmc} and {@code <mapId>.wmc}: chunk files, each holding the tiles of a region of
 * the ground map (with its floors) or of one other map, named by {@link ChunkNames}. The small ones of the other maps are
 * inside {@code small.pack} ({@link SmallPack}) and are read from there: the same chunk, byte for byte;</li>
 * <li>{@code overview-<mapId>.wmo}: an optional whole-map picture at {@link #OVERVIEW_PIXELS}
 * pixels per square.</li>
 * </ul>
 * Everything is generated by the tools in {@code tools/} from the PNG tiles in {@code tools/tile-src}. The plugin never
 * fetches any of it.
 * <p>
 * Reading a tile finds its chunk in a small cache of recently used chunk files (neighbouring squares share one), or
 * reads it from the jar, and decodes just that tile with the codec in {@link com.worldmapplus.tiles.codec}. A chunk that
 * is missing or damaged gives no tile, as a missing picture did, and is logged at debug level. Nothing here throws to the
 * caller and nothing here holds on to more than {@link #CHUNK_BUDGET} bytes of chunk files and a couple of decoders.
 */
@Slf4j
public final class BundledTiles implements TileSource
{
	/** Pixels per map square in the overview pictures, which is 0.5 pixels per game tile. */
	public static final int OVERVIEW_PIXELS = 32;

	/** The most bytes of chunk files kept in memory. The newest chunk is kept even if it alone is larger. */
	static final long CHUNK_BUDGET = 8L << 20;

	/** The largest chunk file read from the jar. The real ones are well under a megabyte; anything larger is not ours. */
	static final int MAX_CHUNK_BYTES = 16 << 20;

	/** The largest overview file read from the jar. */
	static final int MAX_OVERVIEW_BYTES = 16 << 20;

	/** The largest index read from the jar. */
	static final int MAX_INDEX_BYTES = 4 << 20;

	/**
	 * Decoders kept for reuse. A decoder holds about 3 MB of tables for the shipped data and up to about 16 MB at the largest
	 * table size a payload may ask for, and loads rarely run in more than two threads.
	 */
	private static final int MAX_IDLE_DECODERS = 2;

	/** Memory charged per entry of a parsed chunk on top of its bytes: the index and the entry arrays. */
	private static final int ENTRY_OVERHEAD = 96;

	private static final String ROOT = "/com/worldmapplus/tiles/";

	/** Where the files come from: the plugin jar, or something else in tests. */
	interface Resources
	{
		/** Opens a file by its name under the tiles folder, or returns null when there is none. */
		@Nullable
		InputStream open(String name) throws IOException;
	}

	private static final Resources JAR = name -> BundledTiles.class.getResourceAsStream(ROOT + name);

	private final Map<Integer, Set<Integer>> squares;
	private final Resources resources;
	private final long chunkBudget;

	/** Parsed chunks by resource name, least recently used first. Guarded by itself. */
	private final LinkedHashMap<String, ChunkFile> chunks = new LinkedHashMap<>(64, 0.75f, true);
	private final Map<String, Long> chunkSizes = new HashMap<>();
	private long chunkBytes;

	/** Held while a chunk is read from the jar, so two threads never read the same file at once. */
	private final Object readLock = new Object();

	private final Deque<TileDecoder> idleDecoders = new ArrayDeque<>();

	private BundledTiles(Map<Integer, Set<Integer>> squares, Resources resources, long chunkBudget)
	{
		this.squares = squares;
		this.resources = resources;
		this.chunkBudget = chunkBudget;
	}

	/** Packs a square into the key used by the index. */
	public static int key(int x, int y)
	{
		return (x << 16) | (y & 0xFFFF);
	}

	/** Reads the index. A missing or damaged index gives a source with no tiles. */
	public static BundledTiles load(Gson gson)
	{
		return load(gson, JAR);
	}

	static BundledTiles load(Gson gson, Resources resources)
	{
		try (InputStream in = resources.open("index.json"))
		{
			if (in == null)
			{
				log.warn("World Map Plus: the tile index is missing from the plugin jar");
				return new BundledTiles(Collections.emptyMap(), resources, CHUNK_BUDGET);
			}
			byte[] bytes = readCapped(in, MAX_INDEX_BYTES);
			if (bytes == null)
			{
				log.warn("World Map Plus: the tile index is too large to be ours");
				return new BundledTiles(Collections.emptyMap(), resources, CHUNK_BUDGET);
			}
			Index index = gson.fromJson(new String(bytes, StandardCharsets.UTF_8), Index.class);
			return new BundledTiles(parse(index), resources, CHUNK_BUDGET);
		}
		catch (IOException | JsonParseException e)
		{
			log.warn("World Map Plus: could not read the tile index", e);
			return new BundledTiles(Collections.emptyMap(), resources, CHUNK_BUDGET);
		}
	}

	static BundledTiles fromIndex(Map<String, int[]> maps)
	{
		return fromIndex(maps, JAR);
	}

	static BundledTiles fromIndex(Map<String, int[]> maps, Resources resources)
	{
		return fromIndex(maps, resources, CHUNK_BUDGET);
	}

	static BundledTiles fromIndex(Map<String, int[]> maps, Resources resources, long chunkBudget)
	{
		Index index = new Index();
		index.maps = maps;
		return new BundledTiles(parse(index), resources, chunkBudget);
	}

	private static Map<Integer, Set<Integer>> parse(Index index)
	{
		Map<Integer, Set<Integer>> result = new HashMap<>();
		if (index == null || index.maps == null)
		{
			return result;
		}
		for (Map.Entry<String, int[]> entry : index.maps.entrySet())
		{
			int mapId;
			try
			{
				mapId = Integer.parseInt(entry.getKey());
			}
			catch (NumberFormatException e)
			{
				continue;
			}
			Set<Integer> set = new HashSet<>();
			if (entry.getValue() != null)
			{
				for (int value : entry.getValue())
				{
					set.add(value);
				}
			}
			result.put(mapId, set);
		}
		return result;
	}

	@Override
	public boolean exists(int mapId, int x, int y)
	{
		Set<Integer> set = squares.get(mapId);
		return set != null && set.contains(key(x, y));
	}

	/** The highest floor above the ground that this map has tiles for, or 0 when it has none. */
	public int highestFloor(int mapId)
	{
		int highest = 0;
		for (int floor = 1; floor <= MAX_FLOOR; floor++)
		{
			if (tileCount(TileSource.tileMapId(mapId, floor)) > 0)
			{
				highest = floor;
			}
		}
		return highest;
	}

	public int tileCount(int mapId)
	{
		Set<Integer> set = squares.get(mapId);
		return set == null ? 0 : set.size();
	}

	@Nullable
	@Override
	public BufferedImage load(int mapId, int x, int y)
	{
		if (!exists(mapId, x, y))
		{
			return null;
		}
		String name = ChunkNames.chunk(mapId, x, y);
		try
		{
			ChunkFile chunk = chunk(name);
			if (chunk == null)
			{
				return null;
			}
			TileDecoder decoder = borrowDecoder();
			BufferedImage image = chunk.decodeImage(mapId, x, y, mapId >= FLOOR_STRIDE, decoder);
			returnDecoder(decoder);
			return image;
		}
		catch (RuntimeException e)
		{
			// Damaged data gives a CodecException, a RuntimeException. A decoder that failed part way is not given back, so it
			// is never trusted again.
			log.debug("World Map Plus: could not decode tile {}:{}_{} from {}", mapId, x, y, name, e);
			return null;
		}
	}

	@Nullable
	@Override
	public BufferedImage overview(int mapId)
	{
		String name = ChunkNames.overview(mapId);
		try (InputStream in = resources.open(name))
		{
			if (in == null)
			{
				return null;
			}
			byte[] bytes = readCapped(in, MAX_OVERVIEW_BYTES);
			if (bytes == null)
			{
				log.debug("World Map Plus: {} is larger than any overview", name);
				return null;
			}
			// Overviews are decoded with tables much larger than a tile needs, so this decoder is not kept.
			return ImageFile.parse(bytes).decodeImage(false, new TileDecoder());
		}
		catch (IOException | RuntimeException e)
		{
			log.debug("World Map Plus: could not read {}", name, e);
			return null;
		}
	}

	@Nullable
	@Override
	public Picture startOverview(int mapId)
	{
		String name = ChunkNames.overview(mapId);
		try (InputStream in = resources.open(name))
		{
			if (in == null)
			{
				return null;
			}
			byte[] bytes = readCapped(in, MAX_OVERVIEW_BYTES);
			if (bytes == null)
			{
				log.debug("World Map Plus: {} is larger than any overview", name);
				return null;
			}
			// The decoder is the picture's own until it is finished, and then let go of: overviews need much larger tables than a tile.
			return new Sliced(name, ImageFile.parse(bytes).begin(false, new TileDecoder()));
		}
		catch (IOException | RuntimeException e)
		{
			log.debug("World Map Plus: could not read {}", name, e);
			return null;
		}
	}

	/** An overview being decoded a piece at a time. A failure part way gives no picture, as a failure of the whole decode does. */
	private static final class Sliced implements Picture
	{
		private final String name;
		private final TileDecoder.Progress progress;
		private BufferedImage image;
		private boolean failed;

		Sliced(String name, TileDecoder.Progress progress)
		{
			this.name = name;
			this.progress = progress;
		}

		@Override
		public boolean step(long nanos)
		{
			if (failed)
			{
				return true;
			}
			try
			{
				if (progress.step(nanos))
				{
					image = progress.image();
					return true;
				}
				return false;
			}
			catch (RuntimeException e)
			{
				log.debug("World Map Plus: could not decode {}", name, e);
				failed = true;
				return true;
			}
		}

		@Nullable
		@Override
		public BufferedImage image()
		{
			return image;
		}
	}

	/** Lets go of the chunk files and decoders held in memory. The source stays usable and reads them again when asked. */
	@Override
	public void release()
	{
		synchronized (chunks)
		{
			chunks.clear();
			chunkSizes.clear();
			chunkBytes = 0;
		}
		packBytes = null;
		synchronized (idleDecoders)
		{
			idleDecoders.clear();
		}
	}

	/** The parsed chunk of that resource name, from the cache or the jar. Null when the jar has none or it is damaged. */
	@Nullable
	private ChunkFile chunk(String name)
	{
		synchronized (chunks)
		{
			ChunkFile hit = chunks.get(name);
			if (hit != null)
			{
				return hit;
			}
		}
		synchronized (readLock)
		{
			synchronized (chunks)
			{
				ChunkFile raced = chunks.get(name);
				if (raced != null)
				{
					return raced;
				}
			}
			ChunkFile chunk = readChunk(name);
			if (chunk != null)
			{
				remember(name, chunk);
			}
			return chunk;
		}
	}

	/**
	 * The index of small.pack, read the first time a chunk of another map than the ground map is wanted. Null when the jar has
	 * no pack or its header is damaged. Only touched with {@link #readLock} held.
	 */
	@Nullable
	private SmallPack.Index packIndex;
	private boolean packRead;

	/** The bytes of small.pack. Soft: under memory pressure they go and the next packed chunk reads the pack again. */
	@Nullable
	private volatile SoftReference<byte[]> packBytes;

	@Nullable
	private ChunkFile readChunk(String name)
	{
		int base = ChunkNames.packedBase(name);
		if (base >= 0)
		{
			ChunkFile packed = readPacked(name, base);
			if (packed != null)
			{
				return packed;
			}
		}
		try (InputStream in = resources.open(name))
		{
			if (in == null)
			{
				log.debug("World Map Plus: {} is missing from the plugin jar", name);
				return null;
			}
			byte[] bytes = readCapped(in, MAX_CHUNK_BYTES);
			if (bytes == null)
			{
				log.debug("World Map Plus: {} is larger than any chunk", name);
				return null;
			}
			return ChunkFile.parse(bytes);
		}
		catch (IOException | RuntimeException e)
		{
			log.debug("World Map Plus: could not read {}", name, e);
			return null;
		}
	}

	/**
	 * Reads small.pack whole (about 370 KB, inflated once by the jar) and keeps its index. Reading it whole costs one pass over the
	 * bytes, where reaching into the middle of a deflated jar entry for every chunk would inflate half of it each time. Null when
	 * there is no pack or it is damaged; the index stays null then and the pack is not asked for again.
	 */
	@Nullable
	private byte[] readWholePack() throws IOException
	{
		packRead = true;
		try (InputStream in = resources.open(SmallPack.NAME))
		{
			if (in == null)
			{
				return null;
			}
			byte[] all = readCapped(in, SmallPack.MAX_TOTAL_BYTES + 4096);
			if (all == null)
			{
				return null;
			}
			SmallPack.Index index = SmallPack.readIndex(new ByteArrayInputStream(all));
			int last = index.size() - 1;
			if (index.offset(last) + (long) index.length(last) != all.length)
			{
				throw new IOException(SmallPack.NAME + " is not the length its header says");
			}
			packIndex = index;
			packBytes = new SoftReference<>(all);
			return all;
		}
	}

	/** The chunk of a map from small.pack, or null when the pack does not hold it (it may be a loose file) or cannot be read. */
	@Nullable
	private ChunkFile readPacked(String name, int base)
	{
		try
		{
			byte[] all = packBytes == null ? null : packBytes.get();
			if (all == null)
			{
				if (packRead && packIndex == null)
				{
					return null;
				}
				all = readWholePack();
				if (all == null)
				{
					return null;
				}
			}
			int at = packIndex.find(base);
			if (at < 0)
			{
				return null;
			}
			// A copy, so the chunk does not hold the whole pack in memory.
			return ChunkFile.parse(Arrays.copyOfRange(all, packIndex.offset(at), packIndex.offset(at) + packIndex.length(at)));
		}
		catch (IOException | RuntimeException e)
		{
			log.debug("World Map Plus: could not read {} from {}", name, SmallPack.NAME, e);
			return null;
		}
	}

	private void remember(String name, ChunkFile chunk)
	{
		long size = sizeOf(chunk);
		synchronized (chunks)
		{
			chunks.put(name, chunk);
			Long old = chunkSizes.put(name, size);
			chunkBytes += size - (old == null ? 0 : old);
			Iterator<Map.Entry<String, ChunkFile>> it = chunks.entrySet().iterator();
			while (chunkBytes > chunkBudget && chunks.size() > 1 && it.hasNext())
			{
				Map.Entry<String, ChunkFile> eldest = it.next();
				if (eldest.getKey().equals(name))
				{
					continue;
				}
				chunkBytes -= chunkSizes.remove(eldest.getKey());
				it.remove();
			}
		}
	}

	/** What a parsed chunk costs: its bytes, which it keeps, and its tables. */
	private static long sizeOf(ChunkFile chunk)
	{
		return chunk.byteLength() + (long) chunk.size() * ENTRY_OVERHEAD;
	}

	/** Bytes of chunk files held now, for tests. */
	long heldChunkBytes()
	{
		synchronized (chunks)
		{
			return chunkBytes;
		}
	}

	/** Chunk files held now, for tests. */
	int heldChunks()
	{
		synchronized (chunks)
		{
			return chunks.size();
		}
	}

	/** Decoders waiting to be reused, for tests. */
	int idleDecoderCount()
	{
		synchronized (idleDecoders)
		{
			return idleDecoders.size();
		}
	}

	private TileDecoder borrowDecoder()
	{
		synchronized (idleDecoders)
		{
			TileDecoder decoder = idleDecoders.pollFirst();
			if (decoder != null)
			{
				return decoder;
			}
		}
		return new TileDecoder();
	}

	private void returnDecoder(TileDecoder decoder)
	{
		synchronized (idleDecoders)
		{
			if (idleDecoders.size() < MAX_IDLE_DECODERS)
			{
				idleDecoders.addFirst(decoder);
			}
		}
	}

	/**
	 * Reads a stream whole, trusting no length: it stops with null as soon as more than max bytes have come, so a
	 * resource that is not what it should be cannot fill the heap.
	 */
	@Nullable
	static byte[] readCapped(InputStream in, int max) throws IOException
	{
		byte[] buffer = new byte[Math.min(max, 64 << 10) + 1];
		int length = 0;
		while (true)
		{
			if (length == buffer.length)
			{
				if (buffer.length > max)
				{
					return null;
				}
				buffer = Arrays.copyOf(buffer, (int) Math.min((long) buffer.length * 2, (long) max + 1));
			}
			int read = in.read(buffer, length, buffer.length - length);
			if (read < 0)
			{
				break;
			}
			length += read;
		}
		if (length > max)
		{
			return null;
		}
		return length == buffer.length ? buffer : Arrays.copyOf(buffer, length);
	}

	/** The shape of index.json. Filled by Gson. */
	private static final class Index
	{
		private Map<String, int[]> maps;
	}
}
